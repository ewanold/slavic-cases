#!/usr/bin/env python3
"""Refresh committed wheel hashes from version-pinned PyPI release metadata.
No packages are installed. Review resulting locks before using the installer.
"""
import json
from pathlib import Path
from urllib.request import urlopen

PACKAGES = {'PyYAML': '6.0.1', 'PySide6_Essentials': '6.8.3', 'shiboken6': '6.8.3', 'Babel': '2.17.0', 'pip': '25.0.1'}


def main():
    root = Path(__file__).resolve().parents[1] / 'requirements'
    blocks = {}
    for name, version in PACKAGES.items():
        url = f'https://pypi.org/pypi/{name}/{version}/json'
        with urlopen(url, timeout=30) as response:
            release = json.load(response)
        if name == 'pip':
            wheel = next(item for item in release['urls'] if item['filename'].endswith('py3-none-any.whl'))
            (root / 'sample-editor-pip.json').write_text(json.dumps({
                'version': version, 'filename': wheel['filename'], 'url': wheel['url'],
                'sha256': wheel['digests']['sha256']}, indent=2) + '\n', encoding='utf-8')
        hashes = sorted({item['digests']['sha256'] for item in release['urls']
                         if item['filename'].endswith('.whl') and not item.get('yanked')})
        if not hashes:
            raise RuntimeError(f'No wheels for {name}=={version}')
        blocks[name] = f'# {url}\n{name}=={version} \\\n' + ' \\\n'.join('    --hash=sha256:' + value for value in hashes) + '\n'
    (root / 'sample-editor-base.txt').write_text(
        '# Python 3.12; wheels only. Generated by scripts/update-sample-editor-locks.py.\n' +
        blocks['PyYAML'] + blocks['Babel'], encoding='utf-8')
    (root / 'sample-editor-qt.txt').write_text(
        '# Qt Widgets only; no Addons required. Same lock supports Linux and Windows x64.\n' +
        blocks['PySide6_Essentials'] + blocks['shiboken6'], encoding='utf-8')


if __name__ == '__main__':
    main()
